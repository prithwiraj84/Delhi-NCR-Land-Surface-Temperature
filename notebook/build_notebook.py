"""Assemble notebook/sections/*.py (jupytext "percent" format) into delhi_ncr_lst_pipeline.ipynb.

Usage:
    python notebook/build_notebook.py            # writes ../delhi_ncr_lst_pipeline.ipynb
    python notebook/build_notebook.py --check    # also compiles every code cell (syntax check)
    python notebook/build_notebook.py --sections DIR --out X.ipynb   # build from another sections folder

Generated cells (not in the section files):
* the notebook's first code cell ``_CODE_SHA = {"00": "<sha12>", ...}``: the per-section code hashes
  (``section_code_hashes``) that every stage-cache key carries (SPEC §3.1), so edited code never reuses a stale stage;
* ``_lst_enter_section('NN')`` as the first code cell of every section 01-12 (section marker: current section for
  the code hash, elapsed/remaining time, clean stop for LST_STOP_AFTER / the time budget).

Only the standard library + nbformat are needed.
"""
from __future__ import annotations

import argparse
import ast
import hashlib
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SECTIONS_DIR = HERE / "sections"
DEFAULT_OUT = HERE.parent / "delhi_ncr_lst_pipeline.ipynb"

CELL_MARKER = re.compile(r"^# %%(?P<rest>.*)$")
MARKER_COMMENT = "# section marker (generated by build_notebook.py)"
CODE_SHA_COMMENT = ("# Per-section code hashes (generated by build_notebook.py): part of every stage-cache key, so "
                    "edited sections recompute.\n# Edit notebook/sections and rebuild instead of hand-editing cells.")


def section_paths(sections_dir: Path = SECTIONS_DIR) -> list[Path]:
    """The section files ``NN_*.py`` in order."""
    return sorted(Path(sections_dir).glob("[0-9][0-9]_*.py"))


def parse_sections(paths: list[Path]) -> list[tuple[str, str]]:
    """Return a list of (cell_type, source) tuples from percent-format files."""
    cells: list[tuple[str, str]] = []
    for path in paths:
        kind, buf = None, []

        def flush() -> None:
            if kind is None:
                return
            text = "\n".join(buf).strip("\n")
            if not text.strip():
                return
            if kind == "markdown":
                lines = []
                for line in text.splitlines():
                    if line.startswith("# "):
                        lines.append(line[2:])
                    elif line.strip() == "#":
                        lines.append("")
                    else:
                        lines.append(line)
                text = "\n".join(lines)
            cells.append((kind, text))

        for line in path.read_text(encoding="utf-8").splitlines():
            m = CELL_MARKER.match(line)
            if m:
                flush()
                kind = "markdown" if "[markdown]" in m.group("rest") else "code"
                buf = []
            else:
                if kind is None:  # preamble before the first marker is treated as code
                    kind = "code"
                buf.append(line)
        flush()
    return cells


def _strip_docstrings(tree: ast.AST) -> ast.AST:
    """Drop the leading string constant (docstring) of Module / FunctionDef / AsyncFunctionDef / ClassDef bodies."""
    for node in ast.walk(tree):
        if isinstance(node, (ast.Module, ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            body = node.body
            if (body and isinstance(body[0], ast.Expr) and isinstance(body[0].value, ast.Constant)
                    and isinstance(body[0].value.value, str)):
                node.body = body[1:]
    return tree


def _stable_dump(node) -> str:
    """``ast.dump`` that gives the same text on every Python version: fields whose value is None or an empty list are
    left out (``ast.dump`` itself changes between versions, e.g. 3.12 adds ``type_params=[]`` to every def/class and
    3.13 omits empty fields), and no line/column attributes are included."""
    if isinstance(node, ast.AST):
        parts = []
        for field in node._fields:
            value = getattr(node, field, None)
            if value is None or (isinstance(value, list) and not value):
                continue
            parts.append(f"{field}={_stable_dump(value)}")
        return f"{type(node).__name__}({', '.join(parts)})"
    if isinstance(node, list):
        return "[" + ", ".join(_stable_dump(x) for x in node) + "]"
    return repr(node)


def section_code_hash_of(path: Path) -> str:
    """sha1 (12 hex) of the AST of a section's code cells without docstrings: comments, docstrings and markdown never
    change it, any code change does, and the Python version does not (``_stable_dump``)."""
    code = "\n\n".join(src for kind, src in parse_sections([path]) if kind == "code")
    tree = _strip_docstrings(ast.parse(code, filename=str(path)))
    return hashlib.sha1(_stable_dump(tree).encode("utf-8")).hexdigest()[:12]


def section_code_hashes(paths: list[Path]) -> dict[str, str]:
    """{'00': sha12, ..., '12': sha12} for the given section files (key = the file's two-digit prefix)."""
    return {Path(p).name[:2]: section_code_hash_of(Path(p)) for p in paths}


def code_sha_cell(hashes: dict[str, str]) -> str:
    return f"{CODE_SHA_COMMENT}\n_CODE_SHA = {json.dumps(hashes, sort_keys=True)}"


def marker_cell(section_id: str) -> str:
    return f"_lst_enter_section({section_id!r})  {MARKER_COMMENT}"


def notebook_cells(paths: list[Path]) -> list[tuple[str, str]]:
    """All cells: section cells + the generated _CODE_SHA cell (first code cell, after the title markdown) and one
    section-marker cell before the first code cell of every section 01-12."""
    hashes = section_code_hashes(paths)
    out: list[tuple[str, str]] = []
    sha_done = False
    for path in paths:
        sid = path.name[:2]
        marker_done = sid == "00"
        for kind, src in parse_sections([path]):
            if kind == "code":
                if not sha_done:
                    out.append(("code", code_sha_cell(hashes)))
                    sha_done = True
                if not marker_done:
                    out.append(("code", marker_cell(sid)))
                    marker_done = True
            out.append((kind, src))
    if not sha_done:
        out.insert(0, ("code", code_sha_cell(hashes)))
    return out


def build(out_path: Path, check: bool, sections_dir: Path = SECTIONS_DIR) -> None:
    import nbformat
    from nbformat.v4 import new_code_cell, new_markdown_cell, new_notebook

    paths = section_paths(sections_dir)
    if not paths:
        sys.exit(f"No section files found in {sections_dir}")
    cells = notebook_cells(paths)
    if check:
        for i, (kind, src) in enumerate(cells):
            if kind == "code":
                try:
                    compile(src, f"<cell {i}>", "exec")
                except SyntaxError as exc:  # pragma: no cover - reporting path
                    sys.exit(f"Syntax error in code cell {i}: {exc}\n---\n{src[:400]}")
        n_markers = sum(1 for k, s in cells if k == "code" and MARKER_COMMENT in s)
        expected = sum(1 for p in paths if p.name[:2] != "00")
        if n_markers != expected:
            sys.exit(f"expected {expected} section-marker cells, found {n_markers}")
        first_code = next(s for k, s in cells if k == "code")
        if "_CODE_SHA = " not in first_code:
            sys.exit("the first code cell must define _CODE_SHA")
    nb = new_notebook()
    nb.cells = [new_markdown_cell(s) if k == "markdown" else new_code_cell(s) for k, s in cells]
    nb.metadata = {
        "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
        "language_info": {"name": "python", "version": "3.10"},
        "kaggle": {
            "accelerator": "nvidiaTeslaT4",
            "isGpuEnabled": True,
            "isInternetEnabled": True,
            "language": "python",
            "sourceType": "notebook",
        },
    }
    nbformat.validate(nb)
    out_path.write_text(nbformat.writes(nb), encoding="utf-8")
    n_code = sum(1 for k, _ in cells if k == "code")
    print(f"Wrote {out_path} ({len(cells)} cells: {n_code} code, {len(cells) - n_code} markdown) from {len(paths)} "
          f"sections; code hashes {section_code_hashes(paths)}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--check", action="store_true", help="compile every code cell")
    ap.add_argument("--sections", type=Path, default=SECTIONS_DIR, help="folder with the NN_*.py section files")
    args = ap.parse_args()
    build(args.out, args.check, args.sections)
